#!/usr/bin/env python3
"""Generates the privacy policy pages for the GitHub Pages site: python3 build.py (writes <game>/privacy/index.html and index.html)."""
from pathlib import Path

ROOT = Path(__file__).parent
EMAIL = "itsart.developer@gmail.com"
STUDIO = "ItsArt Studios"
UPDATED = "November 22, 2026"

GAMES = [
    {"slug": "bouquetjam", "name": "Bouquet Jam", "package": "com.itsartstudio.boutiquejam", "remote_config": True},
    {"slug": "dropjam", "name": "Drop Jam", "package": "com.itsartstudio.dropjam", "remote_config": False},
    {"slug": "livingchain", "name": "Living Chain", "package": "com.itsartstudio.livingchain", "remote_config": False},
]

CSS = """
:root{--bg:#fbfaf7;--fg:#1d1d1f;--muted:#5f6368;--line:#e3e1da;--accent:#2f6f4f}
@media (prefers-color-scheme:dark){:root{--bg:#141414;--fg:#ececec;--muted:#a0a0a0;--line:#2c2c2c;--accent:#7cc29b}}
*{box-sizing:border-box}
body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.6 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Helvetica,Arial,sans-serif}
main{max-width:720px;margin:0 auto;padding:40px 16px 64px}
h1{font-size:30px;line-height:1.2;margin:0 0 4px}
h2{font-size:19px;margin:32px 0 8px}
p,li{color:var(--fg)}
.meta{color:var(--muted);margin:0 0 24px}
a{color:var(--accent)}
ul{padding-left:22px}
li{margin:4px 0}
footer{margin-top:40px;padding-top:16px;border-top:1px solid var(--line);color:var(--muted);font-size:14px}
"""


def page(title, body):
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>{CSS}</style>
</head>
<body>
<main>
{body}
<footer>&copy; 2026 {STUDIO} &middot; <a href="mailto:{EMAIL}">{EMAIL}</a></footer>
</main>
</body>
</html>
"""


def policy(g):
    name = g["name"]
    services = [
        '<li><strong>Google Analytics for Firebase</strong> &mdash; anonymous usage statistics (<a href="https://firebase.google.com/support/privacy">Firebase privacy information</a>)</li>',
        '<li><strong>Firebase Crashlytics</strong> &mdash; crash and error reports</li>',
    ]
    collected = [
        "an app instance identifier generated by Firebase, and the Android advertising ID where your device makes it available to Firebase Analytics;",
        "device information: device model, operating system version, screen size, language and app version;",
        "approximate location (country or region) derived from your IP address &mdash; never precise GPS location;",
        "how you use the game: sessions, levels played and completed, in-game settings and similar gameplay events;",
        "crash reports: the state of the app and device when a crash or error happens, and an installation identifier.",
    ]
    if g["remote_config"]:
        services.append("<li><strong>Firebase Remote Config</strong> &mdash; lets us adjust game settings without an app update; it uses a Firebase installation identifier</li>")
    body = f"""
<h1>{name} &mdash; Privacy Policy</h1>
<p class="meta">Last updated: {UPDATED}</p>

<p>This privacy policy applies to the {name} game for Android and iOS (Android package <code>{g["package"]}</code>), made by {STUDIO} (&ldquo;we&rdquo;, &ldquo;us&rdquo;). It explains what information the game collects, why, and the choices you have.</p>

<h2>Summary</h2>
<ul>
<li>No account or sign-in. We do not ask for your name, email address, phone number or contacts.</li>
<li>No advertising and no in-app purchases.</li>
<li>We collect anonymous usage statistics and crash reports to understand how the game is played and to fix problems.</li>
<li>We do not sell your data and do not share it for advertising.</li>
</ul>

<h2>Information we collect</h2>
<p>When you play, the following is collected automatically through the Google Firebase services listed below:</p>
<ul>
{"".join(f"<li>{c}</li>" for c in collected)}
</ul>
<p>Your game progress and settings are stored on your device only.</p>

<h2>How we use it</h2>
<ul>
<li>to understand which parts of the game work well and which are too hard or confusing;</li>
<li>to find and fix crashes and bugs;</li>
{"<li>to tune game settings remotely;</li>" if g["remote_config"] else ""}
<li>to keep the game running reliably.</li>
</ul>
<p>We do not use this information to identify you personally, to show you ads or to build an advertising profile.</p>

<h2>Third-party services</h2>
<p>The game uses these services provided by Google LLC, which process the data on our behalf under their own terms and privacy policies:</p>
<ul>
{"".join(services)}
</ul>
<p>See also the <a href="https://policies.google.com/privacy">Google Privacy Policy</a>.</p>

<h2>Sharing</h2>
<p>We do not sell or rent your information. Besides the service providers above, we disclose information only if required by law, or to protect our rights or the safety of others.</p>

<h2>Data retention</h2>
<p>Analytics data is kept no longer than 14 months; crash reports are kept for 90 days. After that they are deleted automatically.</p>

<h2>Your choices</h2>
<ul>
<li>You can stop all collection at any time by uninstalling the game.</li>
<li>You can reset or delete your advertising ID in your device&rsquo;s Google settings.</li>
<li>You can ask us to delete the data associated with your installation, or ask what we hold, by writing to <a href="mailto:{EMAIL}">{EMAIL}</a>. We answer within 30 days.</li>
</ul>

<h2>Children</h2>
<p>{name} is intended for players aged 13 and over and is not directed at children under 13. We do not knowingly collect personal information from children under 13. If you believe a child under 13 has provided us information, contact us and we will delete it.</p>

<h2>Security</h2>
<p>Data is sent over encrypted connections and is stored by Google Firebase with industry-standard safeguards.</p>

<h2>Changes</h2>
<p>We may update this policy from time to time. Changes are published on this page with a new &ldquo;Last updated&rdquo; date.</p>

<h2>Contact</h2>
<p>Questions about privacy in {name}: <a href="mailto:{EMAIL}">{EMAIL}</a>.</p>
"""
    return page(f"{name} Privacy Policy", body)


def support(g):
    name = g["name"]
    body = f"""
<h1>{name} &mdash; Support</h1>
<p class="meta">{STUDIO}</p>

<p>Need help with {name}, found a bug or have an idea? Write to us at
<a href="mailto:{EMAIL}?subject={name.replace(' ', '%20')}">{EMAIL}</a> &mdash; we usually answer within two business days.</p>
<p>To help us fix a problem faster, please mention your device model, its OS version and, if you can, the level where it happened.</p>

<h2>Common questions</h2>
<h3>Is my progress saved?</h3>
<p>Yes, automatically on your device. Deleting the game also deletes the saved progress.</p>
<h3>Does the game need an internet connection?</h3>
<p>No, you can play offline.</p>
<h3>Are there ads or in-app purchases?</h3>
<p>No.</p>
<h3>How do I ask for my data to be deleted?</h3>
<p>Email us from the address above; see the <a href="../privacy/">privacy policy</a> for what is collected.</p>

<p><a href="../privacy/">Privacy Policy</a></p>
"""
    return page(f"{name} Support", body)


def index():
    items = "".join(f'<li>{g["name"]}: <a href="{g["slug"]}/support/">Support</a> &middot; <a href="{g["slug"]}/privacy/">Privacy Policy</a></li>' for g in GAMES)
    return page(f"{STUDIO} Games", f"<h1>{STUDIO} Games</h1><p class=\"meta\">Support and privacy</p><ul>{items}</ul>")


for g in GAMES:
    out = ROOT / g["slug"] / "privacy" / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(policy(g))
    sup = ROOT / g["slug"] / "support" / "index.html"
    sup.parent.mkdir(parents=True, exist_ok=True)
    sup.write_text(support(g))
(ROOT / "index.html").write_text(index())
print("ok")
